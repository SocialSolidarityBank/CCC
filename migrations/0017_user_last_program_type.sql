-- ============================================================================
-- 마이그레이션 0017 — users 에 마지막 선택 사업 컬럼 추가 (D35 · ADR-0014 '개정' 2번)
--
-- `/`로 들어왔을 때 마지막에 보던 사업의 일정으로 직행시키기 위한 값이다. 2026-07-26
-- Q가 브라우저 로컬이 아니라 **계정 설정(DB)**으로 정했다 — 집 컴퓨터와 사무실에서
-- 같은 사업으로 들어가야 한다. 로컬 저장이면 기기를 바꿀 때마다 초기화된다.
--
-- 성격: **본인 계정의 화면 설정**이다. 참여자 데이터도 케이스 데이터도 아니고, 값은
-- 사업 유형 문자열 하나뿐이라 PII 2단 방어(R3) 경로와 무관하다. users.name(0011)·
-- users.time_zone(0005)과 같은 표기/설정 계열 컬럼이다.
--
-- 감사(D14) 판단: **이 컬럼의 쓰기는 audit_log 에 남기지 않는다.** D14가 기록하라고
-- 정한 것은 열람·변경·PII 복호화·내보내기이며 그 대상은 참여자·케이스 기록이다.
-- 본인 UI 설정을 화면 이동마다 기록하면 감사 로그가 내비게이션 흔적으로 덮여 실제
-- 신호(누가 누구의 PII를 봤나)를 찾기 어려워진다 — 감사의 목적을 해친다.
-- 게이트웨이 함수는 값이 실제로 바뀔 때만 UPDATE 를 실행해 쓰기 자체도 최소화한다.
--
-- NULL 허용이라 기존 행은 그대로 둔다. NULL(미선택)이거나 그 사업이 사라졌으면 화면이
-- 첫 사업으로 폴백한다 — 404 를 내지 않는다.
--
-- 이 마이그레이션은 추가(additive) 전용이다. 0001~0016 테이블·트리거를 바꾸지 않는다.
-- ============================================================================

ALTER TABLE users ADD COLUMN last_program_type TEXT;
