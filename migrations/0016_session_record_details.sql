-- Migration 0016 — 정기 기록지 서술형 항목 (CCC-10 · 티켓 #54 · 정기 기록지 설계 v0.2)
--
-- 정기 상담 기록지를 원페이지 스키밍 구조로 개편하면서 새로 저장하게 되는 서술형
-- 항목을 담는 격리 JSON 컬럼 하나를 추가한다. 담는 값은 네 가지(전부 선택):
--
--   * sessionGoalNote   — 이번 상담 목표(D28). 일정에 세션 목표가 연결되지 않은 회차에서
--                         상담사가 기록지에서 바로 적는 값. 일정에 연결된 세션 목표는
--                         기존 schedule_session_goals 가 계속 SSOT 다(중복 저장 아님).
--   * changeSinceLast   — 지난 상담 이후 달라진 일(P3, 설계 §②).
--   * safetyNote        — 위기·안전 확인 서술(P3, 설계 §⑤). 리스크 플래그 확정은 여전히
--                         flags 테이블 + 상담사 선택이다(D9·R5) — 이 값은 서술 기록일 뿐
--                         자동 판정 입력이 아니다.
--   * counselorOpinion  — 담당자 의견(P3, 설계 §⑥). 참여자 발언과 구분되는 상담사 판단.
--
-- 왜 새 컬럼인가(0012·0013 재사용으로 끝내지 못하는 이유):
--   - 0012(액션 4상태)·0013(6영역 스냅샷)은 각각 action_items·session_life_area_snapshots
--     를 이미 덮고 있어 이번 개편에서 추가 컬럼이 필요 없다. 목표 종료+신설(D12)도 기존
--     goals(status·closed_reason·closed_at·replaced_by_goal_id)로 충분하다.
--   - 남는 것은 위 서술형 4종뿐이고, sessions 에는 이를 담을 자리가 없다.
--   - sessions.extra 는 "케이스별 상담사 자유 추가" 확장 슬롯이라 의미가 다르다. 정기
--     기록지의 고정 서술 항목을 자유 슬롯에 섞으면 나중에 구분이 불가능해진다.
--   - 그래서 0014(intake_details)와 같은 방식으로 종류별 서술 전용 컬럼을 하나 더 둔다.
--     코어 3층 구조 준수: 브리핑·통계가 쓰는 코어(6영역·GAS·액션·플래그)는 정규 구조로
--     두고, 서술형은 JSON 으로 격리해 통계 쿼리에 노출하지 않는다.
--
-- 이 마이그레이션은 추가(additive) 전용이다. 0001~0015 테이블·트리거를 바꾸지 않으며,
-- ALTER TABLE ADD COLUMN 이 기존 행을 NULL 로 채우므로 데이터 이관이 필요 없다.
-- db/schema.sql(누적본)에도 같은 정의를 반영한다.
-- ============================================================================

ALTER TABLE sessions ADD COLUMN record_details TEXT;
