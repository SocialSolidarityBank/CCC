-- 마이그레이션 0020 — 개인정보 수집·이용 동의 시각 (D44 · 2026-07-29 Q 결정)
--
-- D44: 동의 3종(① 개인정보 수집·이용 ② 녹음·음성 분석 ③ 텍스트 AI 정리)은 **당사자
-- 등록 시** 받고, **당사자 정보 페이지에서 수정**하며, **인테이크는 읽기만** 한다.
--
-- 왜 support_cases 인가 — 층을 기존 2종과 맞춘다:
--   * 녹음·텍스트 AI 동의는 이미 **두 곳**에 산다. `support_cases.consent_*_at` 이
--     "지금 상태"(현재값)이고, `participant_consent_records`(0008·0014)가 "누가 언제
--     그렇게 기록했나"(append-only 이력)다.
--   * 개인정보 동의는 0014 로 **이력 쪽에만** 들어갔다(participant_consent_records
--     .consent_privacy_at). 즉 빠져 있던 것은 현재값 컬럼 하나뿐이다. 이 마이그레이션이
--     그 반쪽을 채워 3종이 같은 층·같은 모양이 된다.
--
-- 성격 차이 1건(의도한 것): 녹음 동의는 파이프라인 게이트다(미동의면 녹음 업로드 자체가
-- 막힌다 — D15). 개인정보 동의는 게이트가 아니라 **현재 상태 표시·이력의 기준값**이다.
-- 미동의여도 등록·상담은 진행된다(D15 미동의 경로). 이 컬럼으로 어떤 경로도 잠그지 않는다.
--
-- 철회(해제)는 이 컬럼을 NULL 로 되돌리고, 그 행위 자체는 participant_consent_records 에
-- 새 행으로 쌓인다(append-only, D14·D23) — 이력은 UPDATE 로 지우지 않는다.
--
-- 이 마이그레이션은 추가(additive) 전용이다. 0001~0019 테이블·트리거를 바꾸지 않는다.
-- NULL 허용이라 기존 행은 그대로 미동의로 남는다(백필 없음 — 받지 않은 동의를 시스템이
-- 대신 만들어 주면 안 된다).
