const GENERATED_TRAJECTORIES: readonly Trajectory[] = ['improving', 'plateau'];
const WON_FORMATTER = new Intl.NumberFormat('ko-KR');

function generatedName(identityIndex: number): string {
  const zeroBased = identityIndex - 15;
  const familyName = FAMILY_NAMES[Math.floor(zeroBased / GIVEN_NAMES.length)];
  const givenName = GIVEN_NAMES[zeroBased % GIVEN_NAMES.length];
  if (familyName === undefined || givenName === undefined) {
    throw new Error(`[seed] 생성 이름 범위를 벗어났습니다: ${identityIndex}`);
  }
  return `${familyName}${givenName}`;
}

function makeGeneratedParticipant(
  identityIndex: number,
  sessionCount: number,
  archetypeIndex: number,
  helpers: SeedDateHelpers,
): SeedParticipant {
  const archetype = ARCHETYPES[archetypeIndex % ARCHETYPES.length]!;
  const household = HOUSEHOLD_CONTEXTS[(identityIndex + sessionCount) % HOUSEHOLD_CONTEXTS.length]!;
  const monthlyBaseline = 620_000 + identityIndex * 13_000 + sessionCount * 7_000;
  const intakeDay = -(sessionCount * 21 + 35 + (identityIndex % 5));
  const goals = [
    { key: 'primary', title: archetype.goal },
    ...(archetype.secondaryGoal === undefined ? [] : [{ key: 'secondary', title: archetype.secondaryGoal }]),
  ];
  const actionItems: SeedActionSpec[] = [{
    description: archetype.action,
    owner: identityIndex % 3 === 0 ? 'counselor' : 'beneficiary',
    dueDate: helpers.day(intakeDay + 56),
  }];

  const regulars = Array.from({ length: sessionCount - 1 }, (_, regularIndex) => {
    const step = archetype.steps[regularIndex]!;
    const heldDay = intakeDay + (regularIndex + 1) * 21;
    const availableAmount = monthlyBaseline + (regularIndex - 2) * 11_000;
    const lastRegular = regularIndex === sessionCount - 2;
    return {
      heldAt: helpers.at(heldDay, (identityIndex + regularIndex) % 8),
      memo: `${step} 이번 회차에서 다시 계산한 월 가용 금액은 ${WON_FORMATTER.format(availableAmount)}원이었다.`,
      goalLinks: regularIndex % 3 === 2 && goals.length > 1 ? ['primary', 'secondary'] : ['primary'],
      ...(regularIndex === 1 ? { actionItems } : {}),
      ...(lastRegular ? { customQuestions: [archetype.question] } : {}),
    };
  });

  return {
    name: generatedName(identityIndex),
    phone: helpers.phone(identityIndex),
    email: helpers.email(identityIndex),
    assigneeUserId: COUNSELOR_IDS.ai00,
    intakeAt: helpers.at(intakeDay, identityIndex % 8),
    consent: { recordingAi: identityIndex % 11 !== 0 },
    trajectory: GENERATED_TRAJECTORIES[(identityIndex + sessionCount) % GENERATED_TRAJECTORIES.length]!,
    goals,
    intakeMemo: `${archetype.intake} ${household} 최근 석 달 자료로 확인한 월 가용 금액은 약 ${WON_FORMATTER.format(monthlyBaseline)}원이며, 당사자와 상의해 첫 목표를 정했다.`,
    regulars,
    ...(sessionCount >= 5 ? {
      resolvedActions: [{
        description: '초기 상담에서 요청한 서류를 빠짐없이 정리해 제출했다',
        owner: 'beneficiary',
        dueDate: helpers.day(intakeDay + 42),
      } satisfies SeedActionSpec],
    } : {}),
    futureSchedules: [{
      scheduledAt: helpers.at((identityIndex * 5) % 21 + 1, identityIndex % 8),
      goalLinks: ['primary'],
      customQuestions: [archetype.question],
    }],
  };
}

export function fillSessionBuckets(
  curated: readonly SeedParticipant[],
  helpers: SeedDateHelpers,
): readonly SeedParticipant[] {
  const currentCounts = new Map<number, number>();
  for (const participant of curated) {
    const sessionCount = participant.regulars.length + 1;
    currentCounts.set(sessionCount, (currentCounts.get(sessionCount) ?? 0) + 1);
  }

  const generated: SeedParticipant[] = [];
  let identityIndex = 15;
  let archetypeIndex = 0;
  for (let sessionCount = 1; sessionCount <= 10; sessionCount += 1) {
    const existing = currentCounts.get(sessionCount) ?? 0;
    if (existing > 10) {
      throw new Error(`[seed] ${sessionCount}회 사례가 목표 10명을 초과했습니다: ${existing}`);
    }
    for (let slot = existing; slot < 10; slot += 1) {
      generated.push(makeGeneratedParticipant(identityIndex, sessionCount, archetypeIndex, helpers));
      identityIndex += 1;
      archetypeIndex += 1;
    }
  }
  return generated;
}
